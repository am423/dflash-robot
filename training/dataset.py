"""Training dataset for DFlash draft model.

Loads traces generated by trace_generator.py.
Each trace contains:
  - prompt_tokens: prompt token IDs
  - hidden_features: [n_steps, n_capture*hidden] bf16  (target hidden states)
  - next_tokens: [n_steps] ground truth tokens

During training, we:
  1. Randomly sample anchor positions from the response
  2. For each anchor, construct a block: [clean_token, MASK, MASK, ...]
  3. Embed the block using the frozen target embedding table
  4. Feed to draft model with target hidden features as KV injection
  5. Compute position-decayed cross-entropy loss
"""

import math
import random
from pathlib import Path
from typing import Iterator, Optional

import torch
from torch.utils.data import IterableDataset

from config import DRAFT_CONFIG


class DFlashTraceDataset(IterableDataset):
    """Streaming dataset of training traces with random anchor sampling.

    Implements the paper's random anchor strategy (Section 4.2):
      - Randomly sample anchor positions from responses
      - Each anchor = first position of a draft block
      - Block = [clean_token, MASK, MASK, ..., MASK]
      - Exposes draft model to diverse target features

    Also implements position-decayed loss weighting (Equation 4):
      - weight(pos) = exp(-decay * pos)
      - decay = 7 for block_size=16
    """

    def __init__(
        self,
        trace_dir: str,
        block_size: int = 16,
        mask_token_id: int = 151643,
        anchors_per_trace: int = 512,
        max_ctx_len: int = 3072,
        loss_decay: float = 7.0,
        shuffle_files: bool = True,
        seed: int = 42,
    ):
        self.trace_dir = Path(trace_dir)
        self.block_size = block_size
        self.mask_token_id = mask_token_id
        self.anchors_per_trace = anchors_per_trace
        self.max_ctx_len = max_ctx_len
        self.loss_decay = loss_decay

        self.trace_paths = sorted(
            list(self.trace_dir.glob("trace_*.pt")) +
            list(self.trace_dir.glob("trace_*.bin")) +
            list(self.trace_dir.glob("trace_*")))  # catch anything else
        if shuffle_files:
            random.Random(seed).shuffle(self.trace_paths)

    def __iter__(self) -> Iterator[dict]:
        """Yield training batches."""
        worker_info = torch.utils.data.get_worker_info()
        paths = self.trace_paths
        if worker_info is not None:
            per_worker = len(paths) // worker_info.num_workers
            start = worker_info.id * per_worker
            end = start + per_worker if worker_info.id < worker_info.num_workers - 1 else len(paths)
            paths = paths[start:end]

        for path in paths:
            try:
                if path.suffix == '.pt':
                    trace = torch.load(path, map_location="cpu", weights_only=False)
                    yield from self._process_trace(trace)
                elif path.suffix == '.bin' or path.name.startswith('trace_'):
                    yield from self._process_raw_trace(str(path))
            except Exception as e:
                continue

    def _process_raw_trace(self, path: str) -> Iterator[dict]:
        """Process a raw binary trace from test_generate --dump-traces.
        
        Binary format:
          int32_t n_steps
          uint16_t hidden_features[n_steps * feat_dim]  (bf16)
          int32_t  next_tokens[n_steps]
        """
        import struct
        with open(path, 'rb') as f:
            n_steps_bytes = f.read(4)
            if len(n_steps_bytes) < 4:
                return
            n_steps = struct.unpack('<i', n_steps_bytes)[0]
            if n_steps <= 0 or n_steps > 10000:
                return
            
            feat_dim = DRAFT_CONFIG['n_target_features'] * DRAFT_CONFIG['hidden_size']
            feat_bytes = n_steps * feat_dim * 2  # uint16 = 2 bytes
            tok_bytes = n_steps * 4
            
            feat_data = f.read(feat_bytes)
            tok_data = f.read(tok_bytes)
            
            if len(feat_data) < feat_bytes or len(tok_data) < tok_bytes:
                return
            
            # Convert to tensors
            features = torch.frombuffer(
                bytearray(feat_data), dtype=torch.uint16
            ).view(n_steps, feat_dim).to(torch.bfloat16)
            
            tokens = torch.frombuffer(
                bytearray(tok_data), dtype=torch.int32
            )
            
            trace = {
                'hidden_features': features,
                'next_tokens': tokens,
            }
            yield from self._process_trace(trace)

    def _process_trace(self, trace: dict) -> Iterator[dict]:
        """Process one trace: sample anchors, construct blocks, yield batches."""
        hidden_features = trace['hidden_features']  # [n_steps, feat_dim]
        next_tokens = trace['next_tokens']           # [n_steps]
        n_steps = hidden_features.shape[0]

        if n_steps <= self.block_size:
            return

        # Valid anchor range: [0, n_steps - block_size)
        max_anchor = n_steps - self.block_size
        n_anchors = min(self.anchors_per_trace, max_anchor)

        # Random sample anchors (without replacement)
        anchors = sorted(random.sample(range(max_anchor), n_anchors))

        for anchor in anchors:
            # Input: [clean_anchor, MASK, MASK, ..., MASK]
            input_ids = torch.full((self.block_size,), self.mask_token_id, dtype=torch.long)
            input_ids[0] = next_tokens[anchor].item()

            # Target features for this block's context
            # The draft model attends to target features at positions
            # [0..ctx_len) where ctx_len = anchor
            # and positions [ctx_len..ctx_len+q_len) where q_len = block_size
            ctx_len = anchor
            target_hidden = hidden_features[:anchor + self.block_size]  # all needed features

            # Labels: next tokens at positions anchor..anchor+block_size-1
            labels = next_tokens[anchor : anchor + self.block_size].clone()

            # Position-decayed loss weights
            # weight(pos) = exp(-decay * pos), then normalize
            weights = torch.tensor(
                [math.exp(-self.loss_decay * pos) for pos in range(self.block_size)],
                dtype=torch.float32)
            weights = weights / weights.sum()

            yield {
                'input_ids': input_ids,
                'target_hidden': target_hidden,
                'ctx_len': ctx_len,
                'labels': labels,
                'loss_weights': weights,
            }

    def __len__(self) -> int:
        # Approximate: n_traces × anchors_per_trace
        return len(self.trace_paths) * self.anchors_per_trace


def collate_blocks(batch: list[dict]) -> dict:
    """Collate variable-length blocks into a batch.

    Since blocks have varying ctx_len, we can't batch them naively.
    Strategy: return one block at a time (batch_size=1).
    For multi-block batches, we'd need concatenation with sparse attention mask.
    """
    # Single-block mode: return the first block
    block = batch[0]
    return {
        'input_ids': block['input_ids'].unsqueeze(0),      # [1, block_size]
        'target_hidden': block['target_hidden'].unsqueeze(0),  # [1, seq_len, feat_dim]
        'ctx_len': block['ctx_len'],
        'labels': block['labels'].unsqueeze(0),             # [1, block_size]
        'loss_weights': block['loss_weights'].unsqueeze(0),  # [1, block_size]
    }
